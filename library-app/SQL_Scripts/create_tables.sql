/* =========================================================
   LIBRARY DATABASE
   Oracle SQL

   This script creates the tables for the library database, 
   including members, authors, publishers, genres, books, 
   audiobooks, CDs, and magazines.
   ========================================================= */


/* =========================================================
   1. MEMBERS
   ========================================================= */

CREATE TABLE Members (
    member_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(100) NOT NULL,
    last_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(255) NOT NULL,
    phone VARCHAR2(30),
    join_date DATE DEFAULT SYSDATE NOT NULL,
    membership_status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,

    CONSTRAINT pk_members
        PRIMARY KEY (member_id),

    CONSTRAINT uq_members_email
        UNIQUE (email),

    CONSTRAINT chk_members_status
        CHECK (membership_status IN (
            'ACTIVE',
            'INACTIVE',
            'SUSPENDED'
        ))
);


/* =========================================================
   2. AUTHORS
   ========================================================= */

CREATE TABLE Authors (
    author_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR2(100) NOT NULL,
    last_name VARCHAR2(100) NOT NULL,
    birth_year NUMBER(4),
    country VARCHAR2(100),

    CONSTRAINT pk_authors
        PRIMARY KEY (author_id)
);


/* =========================================================
   3. PUBLISHERS
   ========================================================= */

CREATE TABLE Publishers (
    publisher_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    publisher_name VARCHAR2(200) NOT NULL,
    city VARCHAR2(100),
    country VARCHAR2(100),

    CONSTRAINT pk_publishers
        PRIMARY KEY (publisher_id)
);


/* =========================================================
   4. GENRES
   ========================================================= */

CREATE TABLE Genres (
    genre_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    genre_name VARCHAR2(100) NOT NULL,

    CONSTRAINT pk_genres
        PRIMARY KEY (genre_id),

    CONSTRAINT uq_genres_name
        UNIQUE (genre_name)
);


/* =========================================================
   5. BOOKS
   ========================================================= */

CREATE TABLE Books (
    book_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR2(255) NOT NULL,
    isbn VARCHAR2(20),
    publication_year NUMBER(4),
    publisher_id NUMBER,
    genre_id NUMBER,

    CONSTRAINT pk_books
        PRIMARY KEY (book_id),

    CONSTRAINT uq_books_isbn
        UNIQUE (isbn),

    CONSTRAINT fk_books_publisher
        FOREIGN KEY (publisher_id)
        REFERENCES Publishers(publisher_id),

    CONSTRAINT fk_books_genre
        FOREIGN KEY (genre_id)
        REFERENCES Genres(genre_id)
);


/* =========================================================
   6. AUDIOBOOKS
   ========================================================= */

CREATE TABLE Audiobooks (
    audiobook_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR2(255) NOT NULL,
    publication_year NUMBER(4),
    publisher_id NUMBER,
    genre_id NUMBER,
    duration_minutes NUMBER,
    narrator VARCHAR2(200),

    CONSTRAINT pk_audiobooks
        PRIMARY KEY (audiobook_id),

    CONSTRAINT fk_audiobooks_publisher
        FOREIGN KEY (publisher_id)
        REFERENCES Publishers(publisher_id),

    CONSTRAINT fk_audiobooks_genre
        FOREIGN KEY (genre_id)
        REFERENCES Genres(genre_id),

    CONSTRAINT chk_audiobook_duration
        CHECK (duration_minutes > 0)
);


/* =========================================================
   7. CDS
   ========================================================= */

CREATE TABLE CDs (
    cd_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR2(255) NOT NULL,
    artist VARCHAR2(200) NOT NULL,
    release_year NUMBER(4),
    genre_id NUMBER,

    CONSTRAINT pk_cds
        PRIMARY KEY (cd_id),

    CONSTRAINT fk_cds_genre
        FOREIGN KEY (genre_id)
        REFERENCES Genres(genre_id)
);


/* =========================================================
   8. MAGAZINES
   ========================================================= */

CREATE TABLE Magazines (
    magazine_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR2(255) NOT NULL,
    issue_number VARCHAR2(50),
    publication_date DATE,
    publisher_id NUMBER,

    CONSTRAINT pk_magazines
        PRIMARY KEY (magazine_id),

    CONSTRAINT fk_magazines_publisher
        FOREIGN KEY (publisher_id)
        REFERENCES Publishers(publisher_id)
);


/* =========================================================
   9. BOOK AUTHORS
   many-to-many between Books and Authors
   ========================================================= */

CREATE TABLE BookAuthors (
    book_id NUMBER NOT NULL,
    author_id NUMBER NOT NULL,

    CONSTRAINT pk_bookauthors
        PRIMARY KEY (book_id, author_id),

    CONSTRAINT fk_bookauthors_book
        FOREIGN KEY (book_id)
        REFERENCES Books(book_id),

    CONSTRAINT fk_bookauthors_author
        FOREIGN KEY (author_id)
        REFERENCES Authors(author_id)
);


/* =========================================================
   10. LIBRARY ITEMS
   one row represents one library-owned copy/item
   ========================================================= */

CREATE TABLE LibraryItems (
    item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    item_type VARCHAR2(20) NOT NULL,
    book_id NUMBER,
    audiobook_id NUMBER,
    cd_id NUMBER,
    magazine_id NUMBER,
    status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    date_added DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_libraryitems
        PRIMARY KEY (item_id),

    CONSTRAINT fk_libraryitems_book
        FOREIGN KEY (book_id)
        REFERENCES Books(book_id),

    CONSTRAINT fk_libraryitems_audiobook
        FOREIGN KEY (audiobook_id)
        REFERENCES Audiobooks(audiobook_id),

    CONSTRAINT fk_libraryitems_cd
        FOREIGN KEY (cd_id)
        REFERENCES CDs(cd_id),

    CONSTRAINT fk_libraryitems_magazine
        FOREIGN KEY (magazine_id)
        REFERENCES Magazines(magazine_id),

    CONSTRAINT chk_libraryitems_type
        CHECK (item_type IN (
            'BOOK',
            'AUDIOBOOK',
            'CD',
            'MAGAZINE'
        )),

    CONSTRAINT chk_libraryitems_status
        CHECK (status IN (
            'AVAILABLE',
            'CHECKED_OUT',
            'LOST',
            'DAMAGED',
            'MAINTENANCE'
        )),

    CONSTRAINT chk_libraryitems_reference
        CHECK (
            (
                item_type = 'BOOK'
                AND book_id IS NOT NULL
                AND audiobook_id IS NULL
                AND cd_id IS NULL
                AND magazine_id IS NULL
            )

            OR

            (
                item_type = 'AUDIOBOOK'
                AND book_id IS NULL
                AND audiobook_id IS NOT NULL
                AND cd_id IS NULL
                AND magazine_id IS NULL
            )

            OR

            (
                item_type = 'CD'
                AND book_id IS NULL
                AND audiobook_id IS NULL
                AND cd_id IS NOT NULL
                AND magazine_id IS NULL
            )

            OR

            (
                item_type = 'MAGAZINE'
                AND book_id IS NULL
                AND audiobook_id IS NULL
                AND cd_id IS NULL
                AND magazine_id IS NOT NULL
            )
        )
);


/* =========================================================
   11. CHECKOUTS
   ========================================================= */

CREATE TABLE Checkouts (
    checkout_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    member_id NUMBER NOT NULL,
    item_id NUMBER NOT NULL,
    checkout_date DATE DEFAULT SYSDATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE,
    renewal_count NUMBER DEFAULT 0 NOT NULL,

    CONSTRAINT pk_checkouts
        PRIMARY KEY (checkout_id),

    CONSTRAINT fk_checkouts_member
        FOREIGN KEY (member_id)
        REFERENCES Members(member_id),

    CONSTRAINT fk_checkouts_item
        FOREIGN KEY (item_id)
        REFERENCES LibraryItems(item_id),

    CONSTRAINT chk_checkout_due_date
        CHECK (due_date >= checkout_date),

    CONSTRAINT chk_checkout_return_date
        CHECK (
            return_date IS NULL
            OR return_date >= checkout_date
        ),

    CONSTRAINT chk_checkout_renewals
        CHECK (renewal_count >= 0)
);


/* =========================================================
   12. FINES
   ========================================================= */

CREATE TABLE Fines (
    fine_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    checkout_id NUMBER NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    paid_status VARCHAR2(20) DEFAULT 'UNPAID' NOT NULL,
    date_assessed DATE DEFAULT SYSDATE NOT NULL,
    date_paid DATE,

    CONSTRAINT pk_fines
        PRIMARY KEY (fine_id),

    CONSTRAINT fk_fines_checkout
        FOREIGN KEY (checkout_id)
        REFERENCES Checkouts(checkout_id),

    CONSTRAINT chk_fine_amount
        CHECK (amount >= 0),

    CONSTRAINT chk_fine_status
        CHECK (paid_status IN (
            'PAID',
            'UNPAID',
            'WAIVED'
        ))
);